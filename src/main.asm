; ***************************************************************************
;
; Rastan PC Engine port - milestone 1: stage 1 scrolling.
;
; One BG layer (arcade FG composited over BG), 256x224, 64x64 BAT.
; The world (tools/world.py) streams into the BAT as lines of 64 tiles:
; columns of horizontal squares, rows of the castle's upward shafts, in play
; order. Tile patterns go to a pool of VRAM slots on a schedule computed
; offline by tools/pce_stage.py.
;
; Controls: LEFT/RIGHT walk, DOWN crouches, I jumps (UP+I high jump),
; II attacks.
;
; VRAM:  $0000-$0FFF BAT (64x64)
;        $1000-$4BFF streamed BG tiles (tile #$100-#$4BF)
;        $4C00-$4FFF stage prop cells (loaded on demand)
;        $5000-$5BFF Rastan's two sprite pattern buffers (24 cells each)
;        $5C00-$76FF enemy cells (resident)
;        $7700-$7EFF HUD cells
;        $7F00-$7FFF SATB
;
; ***************************************************************************

		include "core.inc"
		.list
		.mlist
		include	"common.asm"
		include	"vdc.asm"

		include	"stage1/stage.inc"	; R1_STAGE_LINES, ... (build/stage1)
		include	"stage2/stage.inc"	; R2_... (build/stage2)
		include	"stage3/stage.inc"
		include	"stage1/coll.inc"
		include	"stage2/coll.inc"
		include	"stage3/coll.inc"
		include	"sound.inc"		; SND_*, SFX_* (build/sound)
		include	"voice.inc"		; VOICE_* (build/voice)
		include	"ending.inc"		; ENDING_*, TITLE_*, GAMEOVER_* (build/still)
		include	"title.inc"
		include	"gameover.inc"
		include	"options.inc"		; CAMERA_TEST (generated by the Makefile)

; Every round's stage data has the same place in its SF2 page (src/rounds.asm):
; these are CPU banks, $40-$7F, with the round's page mapped (sf2_round).
STAGE_BANK0	=	$40		; Line table and records: 16 banks.
QUAD_BANK0	=	$50		; BAT quads: 4.
PAT_BANK0	=	$54		; BG patterns: 26.
COLL_BANK	=	$6E		; The collision map.
PAL_BANK	=	$6F		; Its two sets of BG palettes ($6000, $6200).
PAL_OUT		=	$6000
PAL_CASTLE	=	$6200
; Alike in every round (pce_stage.py: world.py's), so round 1's.
STAGE_LEAD_X	=	R1_STAGE_LEAD_X
STAGE_LEAD_Y	=	R1_STAGE_LEAD_Y
STAGE_ROW_REACH	=	R1_STAGE_ROW_REACH
STAGE_COL_REACH	=	R1_STAGE_COL_REACH
QUAD_SHORT	=	R1_QUAD_SHORT
COLL_PATTERNS	=	R1_COLL_PATTERNS
CASTLE_X	=	R1_CASTLE_X
	.if	(R2_STAGE_LEAD_X != STAGE_LEAD_X) | (R2_STAGE_LEAD_Y != STAGE_LEAD_Y) | (R2_QUAD_SHORT != QUAD_SHORT)
	.fail	the rounds' stage streams differ in their constants
	.endif
	.if	(R3_STAGE_LEAD_X != STAGE_LEAD_X) | (R3_STAGE_LEAD_Y != STAGE_LEAD_Y) | (R3_QUAD_SHORT != QUAD_SHORT)
	.fail	the rounds' stage streams differ in their constants
	.endif
	.if	(R2_COLL_PATTERNS != COLL_PATTERNS) | (R2_CASTLE_X != CASTLE_X)
	.fail	the rounds' collision maps or castles differ in their constants
	.endif
	.if	(R3_COLL_PATTERNS != COLL_PATTERNS) | (R3_CASTLE_X != CASTLE_X)
	.fail	the rounds' collision maps or castles differ in their constants
	.endif

; R1_ONLY - first in a routine of round 1's own: in other rounds it returns at
; once (A changed).
R1_ONLY		.macro
		lda	<cur_round
		dec	a
		beq	* + 3
		rts
		.endm

SATB_ADDR	=	$7F00
MAX_SCROLL_Y	=	512 - 224
START_SCROLL_Y	=	192

; ---------------------------------------------------------------------------
; Zero page.

		.zp
scroll_x:	ds	2		; World X of the screen's left edge.
scroll_y:	ds	2
next_col:	ds	2		; Next stage line to stream into VRAM.
rec_ptr:	ds	2		; Current record read pointer ($6000-$9FFF).
tmp:		ds	2
count:		ds	1
loop_cnt:	ds	2		; Main loop iterations (to detect slow frames).
mawr_hi:	ds	1		; Scratch for stream_line (tmp belongs to stream_ahead).
sl_lo:		ds	1		; More stream_line scratch.
sl_hi:		ds	1
sl_y:		ds	1
ln_flags:	ds	1		; Header of line next_col (line_header): 1 row, 2 door.
ln_idx:		ds	1		; BAT column or row.
ln_trig:	ds	2		; World x of a column, y of a row.
ln_region:	ds	1		; Camera region while it is the next line.
cam_region:	ds	1		; Region of the next line to stream (camera box).
stream_min:	ds	2		; Lines below this stream whatever the camera.
row_top:	ds	2		; World y of the last row streamed ($7FFF: none).
col_last:	ds	2		; World x of the last column streamed ($8000: none).
cv:		ds	2		; smin/smax operands.
bg_set:		ds	1		; BG palettes loaded: 0 outdoors, 1 the castle's.
cl:		ds	2

; ---------------------------------------------------------------------------
; Code.

		.code

core_main:	lda	#GAME_BANK		; (the boot mapping already has it there)
		tam6
		lda	#DEBUG_BANK		; Checkpoints and the debug menu, in MPR2.
		tam2
		stz	<cur_cp
		stz	<dbg_god
		stz	<dbg_noenemy
		stz	<dbg_slow
		stz	<dbg_now
		stz	dbg_wpn
		stz	dbg_ttl
		lda	#1			; (the start screen's menu: round 1,
		sta	dbg_round		; its first checkpoint)
		stz	<dbg_cp
	.if	TITLE
		stz	<dbg_on			; A title: its debug menu is on the start
	.else					; screen only, never in the game.
		lda	#DEBUG_MENU		; Test builds (no title): the menu in the
		sta	<dbg_on			; game (UP + SELECT held), for their warps.
	.endif
		lda	#1			; Round 1, until a game says otherwise.
		sta	<cur_round
		jsr	round_setup		; (and its SF2 page: the one the mapper
		call	init_screen		; starts with is not known)

		cla				; The 16 BG palettes (outdoors).
		jsr	bg_palettes

		jsr	player_init
		jsr	sound_init
		jsr	voice_init
	.if	!CAMERA_TEST
		jsr	hud_init		; (the camera test compares pure BG)
	.endif
		jsr	enemies_init
	.if	!CAMERA_TEST
		jsr	props_init
	.endif
	.if	TITLE
		jsr	title_screen		; (src/still.asm)
	.endif
		jsr	stage_start
		jsr	start_weapon		; (the start screen's choice)

; Main loop: one iteration per frame, starting right after VBLANK.
.frame:		call	wait_vsync
		inc	<loop_cnt
		bne	!+
		inc	<loop_cnt + 1
!:
		jsr	set_scroll_regs		; Show this frame's position.
	.if	!CAMERA_TEST
	.if	BG_CHECK			; Test build: the tile map alone, in the
		lda	<vdc_crl		; colours it was converted with (no
		and	#$BF			; sprites, no colour cycling).
		sta	<vdc_crl
	.else
		lda	<bg_set			; (outdoors only: the castle's palettes
		bne	!+			; have no such colours)
		jsr	dyn_update		; Waterfall cycle, sky change (VBLANK).
!:
	.endif
		jsr	fire_update		; The lava hall's fire (VBLANK).
		jsr	objects_upload		; Changed object poses' cells (VBLANK).
		jsr	sound_update		; Music and effects (the PSG).
		jsr	debug_check		; SELECT: debug menu.
		lda	joytrg			; RUN: pause.
		bit	#JOY_RUN
		beq	!+
		jsr	game_pause
!:
		lda	<loop_cnt		; Debug slow motion: skip logic frames.
		and	<dbg_slow
		bne	.frame
	.endif
	.if	CAMERA_TEST
		jsr	read_input		; Test build: the pad moves the camera.
		jsr	stream_ahead
		lda	<scroll_x		; The palettes of what the middle of the
		clc				; screen shows (it straddles the castle
		adc	#128			; wall here, which the game never shows).
		lda	<scroll_x + 1
		adc	#0
		ldx	#0
		cmp	#>CASTLE_X
		bcc	!+
		inx
!:		cpx	<bg_set
		beq	!+
		txa
		jsr	bg_palettes
!:		jsr	fire_update
	.else
		jsr	player_update		; Compute the next frame.
		lda	<p_door			; Walked into a door.
		beq	!+
		jsr	door_enter
!:
		jsr	props_update		; (the cave block: solid, breakable)
	.if	!NO_ENEMIES
		jsr	enemies_update		; (debug ENEMIES OFF: no walkers)
		jsr	swarm_update		; The hurry-up swarm.
	.endif
		jsr	camera_update
		jsr	stream_ahead		; Make its columns resident.
		jsr	player_draw		; SATB for the next frame.
		jsr	props_draw
		jsr	enemies_draw
		jsr	hud_update
		jsr	checkpoint_track
	.endif
		jmp	.frame

; ---------------------------------------------------------------------------
; bg_palettes - A = 0 (outdoors) or 1 (the castle): load that set of 16 BG
; palettes. The castle has a set of its own (tools/pce_stage.py): the camera
; never shows both, stopping at the gate outside and keeping inside the castle
; wall. bg_palettes_here: the set for where Rastan is. bg_black0 / bg_color0:
; colour 0 black (a cut) / back to the set's.

bg_palettes_here:
		ldx	#0
		lda	<p_x + 1
		cmp	#>CASTLE_X		; (CASTLE_X: low byte 0)
		bcc	!+
		inx
!:		txa
bg_palettes:	sta	<bg_set
		stz	<fire_on		; (the fire's tiles: again, once in)
		stz	col_on			; (and the hanging column's cells)
		php
		sei
		lda	#PAL_BANK		; (in the round's page)
		tam3
		stz	VCE_CTA + 0
		stz	VCE_CTA + 1
		lda	<bg_set
		bne	.castle
		tia	PAL_OUT, VCE_CTW, 512
		plp
		rts
.castle:	tia	PAL_CASTLE, VCE_CTW, 512
		plp
		rts

bg_black0:	php
		sei
		stz	VCE_CTA + 0
		stz	VCE_CTA + 1
		stz	VCE_CTW + 0
		stz	VCE_CTW + 1
		plp
		rts

bg_color0:	php
		sei
		lda	#PAL_BANK
		tam3
		stz	VCE_CTA + 0
		stz	VCE_CTA + 1
		lda	<bg_set
		bne	.castle
		lda	PAL_OUT + 0
		sta	VCE_CTW + 0
		lda	PAL_OUT + 1
		sta	VCE_CTW + 1
		plp
		rts
.castle:	lda	PAL_CASTLE + 0
		sta	VCE_CTW + 0
		lda	PAL_CASTLE + 1
		sta	VCE_CTW + 1
		plp
		rts

; ---------------------------------------------------------------------------
; game_pause - RUN pressed: everything stops, sound too, until RUN again.
; (RUN held with SELECT is still the core's soft reset.)

game_pause:	stz	PSG_VOL			; Silence (the PSG's main volume; the
.wait:		call	wait_vsync		; streams and a voice keep their place).
		lda	joytrg
		bit	#JOY_RUN
		beq	.wait
		lda	#$FF
		sta	PSG_VOL
		rts

; ---------------------------------------------------------------------------
; stage_start - (re)start the stage: with the display off, stream the first
; window of columns, put Rastan at the start and the camera on him.

stage_start:
	.if	!CAMERA_TEST
		jmp	checkpoint_start	; Games restart at the current checkpoint.
	.endif
		call	set_dspoff
		stz	<scroll_x + 0
		stz	<scroll_x + 1
		lda	#<START_SCROLL_Y
		sta	<scroll_y + 0
		lda	#>START_SCROLL_Y
		sta	<scroll_y + 1
		jsr	stream_reset
		jsr	stream_ahead
		jsr	set_scroll_regs
		call	wait_vsync		; SATB DMA, then show the screen.
		call	set_dspon
		rts

; ---------------------------------------------------------------------------
; set_scroll_regs - write scroll_x/scroll_y to BXR/BYR.

set_scroll_regs:
		php				; VDC writes: keep the IRQ out (see stream_line).
		sei
		st0	#VDC_BXR
		lda	<scroll_x + 0
		sta	VDC_DL
		lda	<scroll_x + 1
		and	#$01
		sta	VDC_DH
		st0	#VDC_BYR
		lda	<scroll_y + 0
		sta	VDC_DL
		lda	<scroll_y + 1
		and	#$01
		sta	VDC_DH
		plp
		rts

; ---------------------------------------------------------------------------
; read_input - pad 1 moves the camera (CAMERA_TEST builds, for make test).

read_input:	lda	joynow
		bit	#JOY_R
		beq	.left
		ldx	#2			; Speed 2, or 4 with button I.
		bit	#JOY_B1
		beq	!+
		ldx	#4
!:		txa
		clc
		adc	<scroll_x + 0
		sta	<scroll_x + 0
		bcc	.vert
		inc	<scroll_x + 1
		bra	.vert
.left:		bit	#JOY_L
		beq	.vert
		lda	<scroll_x
		sec
		sbc	#2
		sta	<scroll_x
		bcs	.vert
		dec	<scroll_x + 1
.vert:		lda	joynow
		bit	#JOY_D
		beq	.up
		lda	<scroll_y + 0		; y += 2
		clc
		adc	#2
		sta	<scroll_y + 0
		bcc	.clamp
		inc	<scroll_y + 1
		bra	.clamp
.up:		bit	#JOY_U
		beq	.clamp
		lda	<scroll_y + 0		; y -= 2
		sec
		sbc	#2
		sta	<scroll_y + 0
		bcs	.clamp
		dec	<scroll_y + 1
.clamp:		jmp	camera_clamp

; ---------------------------------------------------------------------------
; stream_reset - nothing streamed yet (next_col 0, no rows, no forced lines).

stream_reset:	jsr	sf2_round
		stz	<next_col
		stz	<next_col + 1
		stz	<stream_min
		stz	<stream_min + 1
		lda	#$FF
		sta	<row_top
		lda	#$7F
		sta	<row_top + 1
		stz	<col_last
		lda	#$80
		sta	<col_last + 1
		stz	<cam_region
		rts

; ---------------------------------------------------------------------------
; stream_ahead - stream lines while the next one is due: a column at x once
; scroll_x + STAGE_LEAD_X >= x, a row at y once scroll_y - STAGE_LEAD_Y <= y,
; any line below stream_min. The door line (the boss room) waits for
; door_enter. Leaves cam_region = the next line's region.

stream_ahead:
.loop:		lda	<next_col		; The end?
		cmp	rd_lines
		lda	<next_col + 1
		sbc	rd_lines + 1
		bcc	!+
		lda	rd_region_end
		sta	<cam_region
		rts
!:		jsr	line_header
		lda	<ln_region
		sta	<cam_region
		lda	<next_col		; Forced?
		cmp	<stream_min
		lda	<next_col + 1
		sbc	<stream_min + 1
		bcc	.go
		lda	<ln_flags
		bit	#2			; The door: wait.
		bne	.done
		lsr	a
		bcs	.row
		lda	<scroll_x		; Column: scroll_x + LEAD - x >= 0?
		clc
		adc	#<STAGE_LEAD_X
		sta	<tmp
		lda	<scroll_x + 1
		adc	#>STAGE_LEAD_X
		sta	<tmp + 1
		lda	<tmp
		sec
		sbc	<ln_trig
		lda	<tmp + 1
		sbc	<ln_trig + 1
		bmi	.done
		bra	.go
.row:		lda	<scroll_y		; Row: y - (scroll_y - LEAD) >= 0?
		sec
		sbc	#<STAGE_LEAD_Y
		sta	<tmp
		lda	<scroll_y + 1
		sbc	#>STAGE_LEAD_Y
		sta	<tmp + 1
		lda	<ln_trig
		sec
		sbc	<tmp
		lda	<ln_trig + 1
		sbc	<tmp + 1
		bmi	.done
.go:		jsr	stream_line
		bra	.loop
.done:		rts

; ---------------------------------------------------------------------------
; line_header - map line next_col's record (MPR3/MPR4), read its header into
; ln_* and leave rec_ptr on its upload count.
;
; Record: u8 flags, u8 BAT column/row, s16 trigger, u8 region;
;         u8 n; n * (u16 tile#, 32 bytes); 64 * u16 BAT words.

line_header:	lda	#STAGE_BANK0		; Pointer table entry = $6000 + next_col * 3.
		tam3
		lda	<next_col + 0
		sta	<rec_ptr + 0
		lda	<next_col + 1
		sta	<rec_ptr + 1
		asl	<rec_ptr + 0		; *2
		rol	<rec_ptr + 1
		lda	<rec_ptr + 0		; + next_col = *3
		clc
		adc	<next_col + 0
		sta	<rec_ptr + 0
		lda	<rec_ptr + 1
		adc	<next_col + 1
		adc	#$60			; Bank mapped at $6000.
		sta	<rec_ptr + 1
		lda	[rec_ptr]		; Bank offset of the record.
		clc
		adc	#STAGE_BANK0
		pha
		ldy	#1
		lda	[rec_ptr], y
		tax
		iny
		lda	[rec_ptr], y
		stx	<rec_ptr + 0
		sta	<rec_ptr + 1
		pla
		tam3				; Record spans $6000-$9FFF.
		inc	a
		tam4
		cly
		lda	[rec_ptr], y
		sta	<ln_flags
		iny
		lda	[rec_ptr], y
		sta	<ln_idx
		iny
		lda	[rec_ptr], y
		sta	<ln_trig
		iny
		lda	[rec_ptr], y
		sta	<ln_trig + 1
		iny
		lda	[rec_ptr], y
		sta	<ln_region
		lda	<rec_ptr		; rec_ptr += 5
		clc
		adc	#5
		sta	<rec_ptr
		bcc	!+
		inc	<rec_ptr + 1
!:		rts

; ---------------------------------------------------------------------------
; stream_line - upload line next_col (after line_header), then next_col++.
;
; The record (tools/pce_stage.py) after its header: u8 n, n uploads of 3 bytes
; (slot lo, pattern # lo, slot hi | pattern # hi << 3), then the line's 64 BAT
; words as codes over 16 quads (4 words each): $00-$DF quad #, $E0-$EF the last
; quad again (1-16 times), $F0-$FF + a byte: quad # 0-4095. Patterns (32 bytes,
; 256 a bank) and quads (8 bytes, 1024 a bank) are dictionaries in the stage's
; SF2 page, read through MPR5 (the collision map's window, put back after).
; A record is under 256 bytes: Y walks it.

stream_line:
		; The VBLANK IRQ selects VDC_CR and, on exit, restores VDC_AR from the
		; core's vdc_reg shadow, which st0 does not update. An IRQ in the middle
		; of an upload would send the rest of it to the wrong register, so VDC
		; sequences run with interrupts held off.
		php
		sei
		tma5
		pha
		lda	#32			; ram_tia: tia src, VDC_DL, 32
		sta	ram_tia + 5
		lda	[rec_ptr]		; Number of tile uploads.
		sta	<count
		ldy	#1
		tax
		beq	.bat

.upload:	lda	[rec_ptr], y		; MAWR = slot * 16
		sta	<sl_lo
		iny
		lda	[rec_ptr], y		; pattern # lo
		sta	<sl_hi
		iny
		lda	[rec_ptr], y		; slot hi | pattern # hi << 3
		iny
		sty	<sl_y
		tax
		and	#7
		sta	<mawr_hi
		lda	<sl_lo
		asl	a
		rol	<mawr_hi
		asl	a
		rol	<mawr_hi
		asl	a
		rol	<mawr_hi
		asl	a
		rol	<mawr_hi
		st0	#VDC_MAWR
		sta	VDC_DL
		lda	<mawr_hi
		sta	VDC_DH
		st0	#VDC_VWR
		txa				; Bank: stage_pats + pattern # >> 8.
		lsr	a
		lsr	a
		lsr	a
		clc
		adc	#PAT_BANK0
		tam5
		lda	<sl_hi			; $A000 + (pattern # & $FF) * 32
		tax
		asl	a
		asl	a
		asl	a
		asl	a
		asl	a
		sta	ram_tia + 1
		txa
		lsr	a
		lsr	a
		lsr	a
		ora	#$A0
		sta	ram_tia + 2
		jsr	ram_tia
		ldy	<sl_y
		dec	<count
		bne	.upload

.bat:		lda	<ln_flags
		lsr	a
		bcs	.row
		; BAT column: VRAM increment 64, MAWR = column. The BAT holds 512 px:
		; the camera may not go back past this column minus that (camera_clamp).
		lda	<ln_trig
		sta	<col_last
		lda	<ln_trig + 1
		sta	<col_last + 1
		st0	#VDC_CR
		lda	<vdc_crl
		sta	VDC_DL
		lda	#$10			; Increment by 64.
		sta	VDC_DH
		st0	#VDC_MAWR
		lda	<ln_idx
		sta	VDC_DL
		st2	#0			; MAWR hi = 0 (row 0).
		bra	.write
.row:		; BAT row: MAWR = row * 64, increment 1. Rows are the shafts';
		; the last one streamed bounds the camera (camera_update).
		lda	<ln_trig
		sta	<row_top
		lda	<ln_trig + 1
		sta	<row_top + 1
		st0	#VDC_MAWR
		lda	<ln_idx
		lsr	a
		lsr	a
		sta	<mawr_hi
		lda	<ln_idx			; (row << 6) & $FF
		asl	a
		asl	a
		asl	a
		asl	a
		asl	a
		asl	a
		sta	VDC_DL
		lda	<mawr_hi
		sta	VDC_DH
.write:		st0	#VDC_VWR
		lda	#8			; ram_tia: one quad, 4 words.
		sta	ram_tia + 5
		lda	#16
		sta	<count
.quad:		lda	[rec_ptr], y
		iny
		cmp	#QUAD_SHORT
		bcc	.short
		cmp	#$F0
		bcs	.long
		and	#$0F			; The last quad again, 1-16 times.
		inc	a
		tax
.again:		jsr	ram_tia
		dec	<count
		dex
		bne	.again
		bra	.next
.long:		and	#$0F			; Quad # hi, then lo.
		sta	<sl_hi
		lda	[rec_ptr], y
		iny
		bra	.map
.short:		stz	<sl_hi
.map:		sta	<sl_lo			; Bank: stage_quads + quad # >> 10.
		lda	<sl_hi
		lsr	a
		lsr	a
		clc
		adc	#QUAD_BANK0
		tam5
		lda	<sl_lo			; $A000 + (quad # & $3FF) * 8
		asl	a
		asl	a
		asl	a
		sta	ram_tia + 1
		lda	<sl_hi			; (hi & 3) << 3 | lo >> 5
		and	#3
		asl	a
		asl	a
		asl	a
		sta	<mawr_hi
		lda	<sl_lo
		lsr	a
		lsr	a
		lsr	a
		lsr	a
		lsr	a
		ora	<mawr_hi
		ora	#$A0
		sta	ram_tia + 2
		jsr	ram_tia
		dec	<count
.next:		lda	<count
		bne	.quad

		lda	#128			; (ram_tia back to its usual length)
		sta	ram_tia + 5
		st0	#VDC_CR			; Back to increment by 1.
		lda	<vdc_crl
		sta	VDC_DL
		st2	#$00
		pla
		tam5

		inc	<next_col + 0
		bne	!+
		inc	<next_col + 1
!:		plp
		rts

