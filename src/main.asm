; ***************************************************************************
;
; Rastan PC Engine port - milestone 1: stage 1 scrolling.
;
; One BG layer (arcade FG composited over BG), 256x224, 64x64 BAT.
; The world (tools/world.py) streams into the BAT as lines of 64 tiles:
; columns of horizontal squares, rows of the castle's upward shafts, in play
; order. Tile patterns go to a pool of VRAM slots on a schedule computed
; offline by tools/pce_stage.py.
;
; Controls: LEFT/RIGHT walk, DOWN crouches, I jumps (UP+I high jump),
; II attacks.
;
; VRAM:  $0000-$0FFF BAT (64x64)
;        $1000-$4BFF streamed BG tiles (tile #$100-#$4BF)
;        $4C00-$4FFF stage prop cells (loaded on demand)
;        $5000-$5BFF Rastan's two sprite pattern buffers (24 cells each)
;        $5C00-$76FF enemy cells (resident)
;        $7700-$7EFF HUD cells
;        $7F00-$7FFF SATB
;
; ***************************************************************************

		include "core.inc"
		.list
		.mlist
		include	"common.asm"
		include	"vdc.asm"

		include	"stage.inc"		; STAGE_LINES, leads, regions
		include	"options.inc"		; CAMERA_TEST (generated by the Makefile)

SATB_ADDR	=	$7F00
MAX_SCROLL_Y	=	512 - 224
START_SCROLL_Y	=	192

; ---------------------------------------------------------------------------
; Zero page.

		.zp
scroll_x:	ds	2		; World X of the screen's left edge.
scroll_y:	ds	2
next_col:	ds	2		; Next stage line to stream into VRAM.
rec_ptr:	ds	2		; Current record read pointer ($6000-$9FFF).
tmp:		ds	2
count:		ds	1
loop_cnt:	ds	2		; Main loop iterations (to detect slow frames).
mawr_hi:	ds	1		; Scratch for stream_line (tmp belongs to stream_ahead).
ln_flags:	ds	1		; Header of line next_col (line_header): 1 row, 2 door.
ln_idx:		ds	1		; BAT column or row.
ln_trig:	ds	2		; World x of a column, y of a row.
ln_region:	ds	1		; Camera region while it is the next line.
cam_region:	ds	1		; Region of the next line to stream (camera box).
stream_min:	ds	2		; Lines below this stream whatever the camera.
row_top:	ds	2		; World y of the last row streamed ($7FFF: none).
col_last:	ds	2		; World x of the last column streamed ($8000: none).
cv:		ds	2		; smin/smax operands.
cl:		ds	2

; ---------------------------------------------------------------------------
; Code.

		.code

core_main:	lda	#GAME_BANK		; (the boot mapping already has it there)
		tam6
		lda	#DEBUG_BANK		; Checkpoints and the debug menu, in MPR2.
		tam2
		stz	<cur_cp
		stz	<dbg_god
		stz	<dbg_noenemy
		stz	<dbg_slow
		call	init_screen

		; Load all 16 BG palettes.
		lda	#^palette_data
		tam3
		stz	VCE_CTA + 0
		stz	VCE_CTA + 1
		tia	palette_data, VCE_CTW, 512

		jsr	player_init
	.if	!CAMERA_TEST
		jsr	hud_init		; (the camera test compares pure BG)
	.endif
		jsr	enemies_init
	.if	!CAMERA_TEST
		jsr	props_init
	.endif
		jsr	stage_start

; Main loop: one iteration per frame, starting right after VBLANK.
.frame:		call	wait_vsync
		inc	<loop_cnt
		bne	!+
		inc	<loop_cnt + 1
!:
		jsr	set_scroll_regs		; Show this frame's position.
	.if	!CAMERA_TEST
		jsr	dyn_update		; Waterfall cycle, sky change (VBLANK).
		jsr	objects_upload		; Changed object poses' cells (VBLANK).
		jsr	debug_check		; SELECT: debug menu.
		lda	<loop_cnt		; Debug slow motion: skip logic frames.
		and	<dbg_slow
		bne	.frame
	.endif
	.if	CAMERA_TEST
		jsr	read_input		; Test build: the pad moves the camera.
		jsr	stream_ahead
	.else
		jsr	player_update		; Compute the next frame.
		lda	<p_door			; Walked into a door.
		beq	!+
		jsr	door_enter
!:
		jsr	props_update		; (the cave block: solid, breakable)
	.if	!NO_ENEMIES
		jsr	enemies_update		; (debug ENEMIES OFF: no walkers)
	.endif
		jsr	camera_update
		jsr	stream_ahead		; Make its columns resident.
		jsr	player_draw		; SATB for the next frame.
		jsr	props_draw
		jsr	enemies_draw
		jsr	hud_update
		jsr	checkpoint_track
	.endif
		jmp	.frame

; ---------------------------------------------------------------------------
; stage_start - (re)start the stage: with the display off, stream the first
; window of columns, put Rastan at the start and the camera on him.

stage_start:
	.if	!CAMERA_TEST
		jmp	checkpoint_start	; Games restart at the current checkpoint.
	.endif
		call	set_dspoff
		stz	<scroll_x + 0
		stz	<scroll_x + 1
		lda	#<START_SCROLL_Y
		sta	<scroll_y + 0
		lda	#>START_SCROLL_Y
		sta	<scroll_y + 1
		jsr	stream_reset
		jsr	stream_ahead
		jsr	set_scroll_regs
		call	wait_vsync		; SATB DMA, then show the screen.
		call	set_dspon
		rts

; ---------------------------------------------------------------------------
; set_scroll_regs - write scroll_x/scroll_y to BXR/BYR.

set_scroll_regs:
		php				; VDC writes: keep the IRQ out (see stream_line).
		sei
		st0	#VDC_BXR
		lda	<scroll_x + 0
		sta	VDC_DL
		lda	<scroll_x + 1
		and	#$01
		sta	VDC_DH
		st0	#VDC_BYR
		lda	<scroll_y + 0
		sta	VDC_DL
		lda	<scroll_y + 1
		and	#$01
		sta	VDC_DH
		plp
		rts

; ---------------------------------------------------------------------------
; read_input - pad 1 moves the camera (CAMERA_TEST builds, for make test).

read_input:	lda	joynow
		bit	#JOY_R
		beq	.left
		ldx	#2			; Speed 2, or 4 with button I.
		bit	#JOY_B1
		beq	!+
		ldx	#4
!:		txa
		clc
		adc	<scroll_x + 0
		sta	<scroll_x + 0
		bcc	.vert
		inc	<scroll_x + 1
		bra	.vert
.left:		bit	#JOY_L
		beq	.vert
		lda	<scroll_x
		sec
		sbc	#2
		sta	<scroll_x
		bcs	.vert
		dec	<scroll_x + 1
.vert:		lda	joynow
		bit	#JOY_D
		beq	.up
		lda	<scroll_y + 0		; y += 2
		clc
		adc	#2
		sta	<scroll_y + 0
		bcc	.clamp
		inc	<scroll_y + 1
		bra	.clamp
.up:		bit	#JOY_U
		beq	.clamp
		lda	<scroll_y + 0		; y -= 2
		sec
		sbc	#2
		sta	<scroll_y + 0
		bcs	.clamp
		dec	<scroll_y + 1
.clamp:		jmp	camera_clamp

; ---------------------------------------------------------------------------
; stream_reset - nothing streamed yet (next_col 0, no rows, no forced lines).

stream_reset:	stz	<next_col
		stz	<next_col + 1
		stz	<stream_min
		stz	<stream_min + 1
		lda	#$FF
		sta	<row_top
		lda	#$7F
		sta	<row_top + 1
		stz	<col_last
		lda	#$80
		sta	<col_last + 1
		stz	<cam_region
		rts

; ---------------------------------------------------------------------------
; stream_ahead - stream lines while the next one is due: a column at x once
; scroll_x + STAGE_LEAD_X >= x, a row at y once scroll_y - STAGE_LEAD_Y <= y,
; any line below stream_min. The door line (the boss room) waits for
; door_enter. Leaves cam_region = the next line's region.

stream_ahead:
.loop:		lda	<next_col		; The end?
		cmp	#<STAGE_LINES
		lda	<next_col + 1
		sbc	#>STAGE_LINES
		bcc	!+
		lda	#STAGE_REGION_END
		sta	<cam_region
		rts
!:		jsr	line_header
		lda	<ln_region
		sta	<cam_region
		lda	<next_col		; Forced?
		cmp	<stream_min
		lda	<next_col + 1
		sbc	<stream_min + 1
		bcc	.go
		lda	<ln_flags
		bit	#2			; The door: wait.
		bne	.done
		lsr	a
		bcs	.row
		lda	<scroll_x		; Column: scroll_x + LEAD - x >= 0?
		clc
		adc	#<STAGE_LEAD_X
		sta	<tmp
		lda	<scroll_x + 1
		adc	#>STAGE_LEAD_X
		sta	<tmp + 1
		lda	<tmp
		sec
		sbc	<ln_trig
		lda	<tmp + 1
		sbc	<ln_trig + 1
		bmi	.done
		bra	.go
.row:		lda	<scroll_y		; Row: y - (scroll_y - LEAD) >= 0?
		sec
		sbc	#<STAGE_LEAD_Y
		sta	<tmp
		lda	<scroll_y + 1
		sbc	#>STAGE_LEAD_Y
		sta	<tmp + 1
		lda	<ln_trig
		sec
		sbc	<tmp
		lda	<ln_trig + 1
		sbc	<tmp + 1
		bmi	.done
.go:		jsr	stream_line
		bra	.loop
.done:		rts

; ---------------------------------------------------------------------------
; line_header - map line next_col's record (MPR3/MPR4), read its header into
; ln_* and leave rec_ptr on its upload count.
;
; Record: u8 flags, u8 BAT column/row, s16 trigger, u8 region;
;         u8 n; n * (u16 tile#, 32 bytes); 64 * u16 BAT words.

line_header:	lda	#^stage_data		; Pointer table entry = stage_data + next_col * 3.
		tam3
		lda	<next_col + 0
		sta	<rec_ptr + 0
		lda	<next_col + 1
		sta	<rec_ptr + 1
		asl	<rec_ptr + 0		; *2
		rol	<rec_ptr + 1
		lda	<rec_ptr + 0		; + next_col = *3
		clc
		adc	<next_col + 0
		sta	<rec_ptr + 0
		lda	<rec_ptr + 1
		adc	<next_col + 1
		adc	#$60			; Bank mapped at $6000.
		sta	<rec_ptr + 1
		lda	[rec_ptr]		; Bank offset of the record.
		clc
		adc	#^stage_data
		pha
		ldy	#1
		lda	[rec_ptr], y
		tax
		iny
		lda	[rec_ptr], y
		stx	<rec_ptr + 0
		sta	<rec_ptr + 1
		pla
		tam3				; Record spans $6000-$9FFF.
		inc	a
		tam4
		cly
		lda	[rec_ptr], y
		sta	<ln_flags
		iny
		lda	[rec_ptr], y
		sta	<ln_idx
		iny
		lda	[rec_ptr], y
		sta	<ln_trig
		iny
		lda	[rec_ptr], y
		sta	<ln_trig + 1
		iny
		lda	[rec_ptr], y
		sta	<ln_region
		lda	<rec_ptr		; rec_ptr += 5
		clc
		adc	#5
		sta	<rec_ptr
		bcc	!+
		inc	<rec_ptr + 1
!:		rts

; ---------------------------------------------------------------------------
; stream_line - upload line next_col (after line_header), then next_col++.

stream_line:
		; The VBLANK IRQ selects VDC_CR and, on exit, restores VDC_AR from the
		; core's vdc_reg shadow, which st0 does not update. An IRQ in the middle
		; of an upload would send the rest of it to the wrong register, so VDC
		; sequences run with interrupts held off.
		php
		sei
		lda	[rec_ptr]		; Number of tile uploads.
		sta	<count
		jsr	inc_ptr_1
		lda	<count
		beq	.bat

.upload:	; MAWR = tile# * 16
		ldy	#1
		lda	[rec_ptr], y		; tile# hi
		sta	<mawr_hi
		lda	[rec_ptr]		; tile# lo
		asl	a
		rol	<mawr_hi
		asl	a
		rol	<mawr_hi
		asl	a
		rol	<mawr_hi
		asl	a
		rol	<mawr_hi
		st0	#VDC_MAWR
		sta	VDC_DL
		lda	<mawr_hi
		sta	VDC_DH
		st0	#VDC_VWR

		ldy	#2			; 32 bytes of pattern.
.pat:		lda	[rec_ptr], y
		sta	VDC_DL
		iny
		lda	[rec_ptr], y
		sta	VDC_DH
		iny
		cpy	#34
		bne	.pat

		lda	<rec_ptr + 0		; rec_ptr += 34
		clc
		adc	#34
		sta	<rec_ptr + 0
		bcc	!+
		inc	<rec_ptr + 1
!:		dec	<count
		bne	.upload

.bat:		lda	<ln_flags
		lsr	a
		bcs	.row
		; BAT column: VRAM increment 64, MAWR = column. The BAT holds 512 px:
		; the camera may not go back past this column minus that (camera_clamp).
		lda	<ln_trig
		sta	<col_last
		lda	<ln_trig + 1
		sta	<col_last + 1
		st0	#VDC_CR
		lda	<vdc_crl
		sta	VDC_DL
		lda	#$10			; Increment by 64.
		sta	VDC_DH
		st0	#VDC_MAWR
		lda	<ln_idx
		sta	VDC_DL
		st2	#0			; MAWR hi = 0 (row 0).
		bra	.write
.row:		; BAT row: MAWR = row * 64, increment 1. Rows are the shafts';
		; the last one streamed bounds the camera (camera_update).
		lda	<ln_trig
		sta	<row_top
		lda	<ln_trig + 1
		sta	<row_top + 1
		st0	#VDC_MAWR
		lda	<ln_idx
		lsr	a
		lsr	a
		sta	<mawr_hi
		lda	<ln_idx			; (row << 6) & $FF
		asl	a
		asl	a
		asl	a
		asl	a
		asl	a
		asl	a
		sta	VDC_DL
		lda	<mawr_hi
		sta	VDC_DH
.write:		st0	#VDC_VWR
		cly
.batloop:	lda	[rec_ptr], y
		sta	VDC_DL
		iny
		lda	[rec_ptr], y
		sta	VDC_DH
		iny
		cpy	#128			; 64 words.
		bne	.batloop

		st0	#VDC_CR			; Back to increment by 1.
		lda	<vdc_crl
		sta	VDC_DL
		st2	#$00

		inc	<next_col + 0
		bne	!+
		inc	<next_col + 1
!:		plp
		rts

inc_ptr_1:	inc	<rec_ptr + 0
		bne	!+
		inc	<rec_ptr + 1
!:		rts

; ---------------------------------------------------------------------------
; init_screen - 256x224, 64x64 BAT, SATB at $7F00, display off.

init_screen	.proc
		php
		sei
		call	clear_vce
		lda.l	#$100			; Fill BAT with tile #$100.
		sta.l	<_ax
		lda.h	#$100
		sta.h	<_ax
		lda	#>(64 * 64)		; BAT size in words / 256.
		sta	<_bl
		call	clear_vram_vdc
		lda	#<.mode
		sta.l	<_bp
		lda	#>.mode
		sta.h	<_bp
		ldy	#^.mode
		call	set_mode_vdc
		bit	VDC_SR
		plp
		call	wait_vsync
		leave

.mode:		db	$80
		db	VCE_CR_5MHz + XRES_SOFT
		db	VDC_MWR
		dw	VDC_MWR_64x64 + VDC_MWR_1CYCLE
		db	VDC_HSR
		dw	VDC_HSR_256
		db	VDC_HDR
		dw	VDC_HDR_256
		db	VDC_VPR
		dw	VDC_VPR_224
		db	VDC_VDW
		dw	VDC_VDW_224
		db	VDC_VCR
		dw	VDC_VCR_224
		db	VDC_DCR
		dw	$0010			; Auto VRAM->SATB each VBLANK.
		db	VDC_DVSSR
		dw	SATB_ADDR
		db	VDC_BXR
		dw	$0000
		db	VDC_BYR
		dw	$0000
		db	VDC_RCR
		dw	$0000
		db	VDC_CR
		dw	$000C			; VSYNC & RCR IRQ enable.
		db	0
		.endp

