"""Turn the arcade's MSM5205 voice samples into PC Engine D/A streams.

usage: pce_voice.py adpcm.bin outdir

Rastan's jump grunt and death cry are not FM: the sound board plays them on an
MSM5205 from its own ADPCM ROM (the Z80 writes the start page to $B000 and
starts it at $C000). The PC Engine has no ADPCM, but each PSG channel has a
direct D/A mode: put the channel in DDA and every write to its waveform port
sets the output level there and then. src/voice.asm does that from the H6280's
timer interrupt, so what this writes is one 5-bit level per timer tick.

Rates. The ADPCM ROM holds the samples back to back, so a sample's data runs
from its own start page to the next sample's. sim/snd shows the driver starting
and stopping each one, and the two long samples give
  $28->$63  30208 nibbles in 253 frames = 7164 Hz
  $63->$b1  39936 nibbles in 335 frames = 7152 Hz
so the MSM5205 is running at about 7158 Hz here. The PC Engine's timer ticks at
7.16 MHz / 1024 = 6991 Hz, 2% slower, so each sample is resampled to keep the
arcade's own pitch and length.

Outputs:
  voice.bin   the samples, one after another, each ending in a $80 stop byte
  voice.inc   VOICE_* numbers and their bank/address tables
"""
import os
import sys
import numpy as np

ARCADE_RATE = 7158.0            # MSM5205, measured above
PCE_RATE = 7159090.0 / 1024     # H6280 timer with TIMER_DR = 0: 6991 Hz
FADE = 64                       # samples of fade-out where the driver cuts it

# name, start page in the ADPCM ROM, end page, how long the driver plays it
# (frames between its writes to $C000 and $D000, from sim/snd).
VOICES = [
    ('JUMP', 0x02, 0x07, 20),   # command $0a, as Rastan leaves the ground
    ('DIE', 0x07, 0x28, 138),   # command $0d
]

STEP = [16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
        107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449,
        494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552]
ADJUST = [-1, -1, -1, -1, 2, 4, 6, 8]


def decode(nibs):
    """MSM5205 ADPCM: each nibble is a sign and a fraction of the current step."""
    sig, idx = 0, 0
    out = np.empty(len(nibs), np.int32)
    for i, n in enumerate(nibs):
        st = STEP[idx]
        d = st >> 3
        if n & 4:
            d += st
        if n & 2:
            d += st >> 1
        if n & 1:
            d += st >> 2
        sig = max(-2048, min(2047, sig - d if n & 8 else sig + d))
        out[i] = sig
        idx = max(0, min(48, idx + ADJUST[n & 7]))
    return out


def nibbles(data):
    """High nibble first (the other order drives the decoder into its clamp)."""
    out = np.empty(len(data) * 2, np.uint8)
    out[0::2] = data >> 4
    out[1::2] = data & 15
    return out


def sample(rom, page0, page1, frames):
    """One voice as PSG levels 0-31, at the PC Engine's timer rate."""
    s = decode(nibbles(rom[page0 << 8:page1 << 8])).astype(np.float64)
    s = s[:int(round(frames / 60.0 * ARCADE_RATE))]      # the driver cuts it here
    s[-FADE:] *= np.linspace(1.0, 0.0, min(FADE, len(s)))
    n = int(round(len(s) * PCE_RATE / ARCADE_RATE))      # 7158 Hz -> 6991 Hz
    s = np.interp(np.arange(n) * (len(s) - 1) / (n - 1), np.arange(len(s)), s)
    s -= s.mean()
    s *= 15.5 / max(1.0, np.abs(s).max())                # the full 5-bit range
    return np.clip(np.round(s + 15.5), 0, 31).astype(np.uint8)


def main():
    rom = np.frombuffer(open(sys.argv[1], 'rb').read(), np.uint8)
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    blob, entries = bytearray(), []
    for name, page0, page1, frames in VOICES:
        s = sample(rom, page0, page1, frames)
        entries.append((name, len(blob)))
        blob += s.tobytes() + b'\x80'                    # $80: stop (levels are 0-31)
        print(f'{name}: ADPCM ${page0:02x}00-${page1:02x}00, {frames} frames'
              f' -> {len(s)} samples ({len(s) / PCE_RATE:.2f}s)')
    open(f'{out}/voice.bin', 'wb').write(blob)
    with open(f'{out}/voice.inc', 'w') as f:
        f.write('; Generated by tools/pce_voice.py\n')
        for i, (name, _) in enumerate(entries):
            f.write(f'VOICE_{name}\t= {i}\n')
        f.write(f'VOICE_COUNT\t= {len(entries)}\n')
        f.write(f'VOICE_BYTES\t= {len(blob)}\n\n')
        for part, shift in (('bank', None), ('lo', 0), ('hi', 8)):
            vals = [f'^voice_data + {off // 8192}' if part == 'bank'
                    else f'(${0x6000 + off % 8192:04X} >> {shift}) & $FF'
                    for _, off in entries]
            f.write(f'voice_tbl_{part}:\tdb\t' + ', '.join(vals) + '\n')
    print(f'voice.bin {len(blob)} bytes ({(len(blob) + 8191) // 8192} banks)')


if __name__ == '__main__':
    main()
