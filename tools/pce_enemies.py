"""Build enemy sprite data for the PC Engine from arcade captures.

usage: pce_enemies.py lizard.snp outdir

The arcade draws objects from 16x16 PC090OJ pieces, which are also the PCE's
16x16 sprite cell size, so each unique arcade piece (code + palette) becomes one
PCE cell, and a pose is a list of (dx, dy, cell, flip) relative to the object's
anchor. All enemy cells stay resident in VRAM.

Sequences are captured from the run in sim/scripts/lizard.txt (Rastan stands at
the start with his health held; lizardmen walk up, attack him, and are killed by
his periodic swings), using the object slot and frame ranges below.

Outputs:
  enemies.bin  cells (128 bytes each, PCE sprite format)
  enemies.inc  ENEMY_CELLS, pose tables, animation tables
  enepal.bin   sprite palettes 1.. (16 colors each) used by the cells
  enemies.png  preview
"""
import os
import sys
import numpy as np
from PIL import Image
from arcade_gfx import load_region, decode_packed
from snap import read_snaps, palette_rgb
from enemy_capture import slot_pieces

ROMDIR = os.environ.get('RASTAN_ROMS', os.path.join(os.path.dirname(__file__), '..', 'roms', 'rastan'))

# (name, slot, first frame, last frame) in the lizard run; consecutive frames
# with the same layout collapse into one pose with a duration.
SEQUENCES = [
    ('liz_walk', 8, 420, 451),
    ('liz_attack', 8, 658, 697),
    ('liz_death', 8, 1536, 1566),
]


def norm(p):
    mx = min(q[3] for q in p)
    my = min(q[1] for q in p)
    return tuple(sorted((a, dy - my, c, dx - mx) for a, dy, c, dx in p))


def main():
    snapf, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    spr = decode_packed(load_region(ROMDIR, 'pc090oj'), 16, 16).astype(int)
    frames = {}
    want = {f for _, _, a, b in SEQUENCES for f in range(a, b + 1)}
    pal = colbank = None
    for s in read_snaps(snapf):
        if s.frame in want:
            frames[s.frame] = s
            if pal is None:
                pal, colbank = palette_rgb(s.pal), (s.sprctrl & 0xe0) >> 1

    poses, pose_ids, anims = [], {}, {}
    for name, slot, a, b in SEQUENCES:
        seq = []
        for f in range(a, b + 1):
            p = slot_pieces(frames[f], slot)
            if not p:
                continue
            k = norm(p)
            if k not in pose_ids:
                pose_ids[k] = len(poses)
                poses.append(p)           # keep the first capture's offsets
            pid = pose_ids[k]
            if seq and seq[-1][0] == pid:
                seq[-1][1] += 1
            else:
                seq.append([pid, 1])
        anims[name] = seq

    # Cells: unique (code, arcade palette). Colors per arcade palette -> PCE palette.
    cells, cell_ids = [], {}
    pal_ids = {}
    for p in poses:
        for attr, dy, code, dx in p:
            ap = (attr & 0xf) | colbank
            pal_ids.setdefault(ap, len(pal_ids))
            key = (code, ap)
            if key not in cell_ids:
                cell_ids[key] = len(cells)
                cells.append(key)
    assert len(pal_ids) <= 15

    def to9(c):
        return tuple(int(round(int(v) * 7 / 255)) for v in c)

    blob = bytearray()
    for code, ap in cells:
        g = spr[code]
        b = bytearray(128)
        for pl in range(4):
            for y in range(16):
                v = 0
                for x in range(16):
                    if (g[y, x] >> pl) & 1:
                        v |= 0x8000 >> x
                b[pl * 32 + y * 2] = v & 0xff
                b[pl * 32 + y * 2 + 1] = v >> 8
        blob += b
    open(f'{out}/enemies.bin', 'wb').write(blob)

    vce = bytearray()
    for ap in sorted(pal_ids, key=pal_ids.get):
        for i in range(16):
            r, g, b = to9(pal[ap * 16 + i])
            vce += ((g << 6) | (r << 3) | b).to_bytes(2, 'little')
    open(f'{out}/enepal.bin', 'wb').write(vce)

    with open(f'{out}/enemies.inc', 'w') as f:
        f.write('; Generated by tools/pce_enemies.py\n')
        f.write(f'ENEMY_CELLS\t= {len(cells)}\nENEMY_PALS\t= {len(pal_ids)}\n\n')
        f.write('; Pose: count, then per piece: dx, dy, cell, attr\n')
        f.write(';   attr bits 0-3 PCE sprite palette (1 + n), bit 6 = arcade X flip, bit 7 = Y flip\n')
        for i, p in enumerate(poses):
            f.write(f'epose_{i}:\t\tdb\t{len(p)}\n')
            for attr, dy, code, dx in p:
                ap = (attr & 0xf) | colbank
                a = (1 + pal_ids[ap]) | (0x40 if attr & 0x4000 else 0) | (0x80 if attr & 0x8000 else 0)
                f.write(f'\t\tdb\t{dx & 0xff}, {dy & 0xff}, {cell_ids[(code, ap)]}, ${a:02X}\n')
        f.write('\nepose_table:\n')
        for i in range(len(poses)):
            f.write(f'\t\tdw\tepose_{i}\n')
        f.write('\n; Animations: (pose, frames) pairs, $FF end\n')
        for name, seq in anims.items():
            f.write(f'anim_{name}:\n')
            for pid, d in seq:
                f.write(f'\t\tdb\t{pid}, {d}\n')
            f.write('\t\tdb\t$FF, $FF\n')

    # Preview: each pose on a 96x96 canvas, anchor at (48, 72).
    pv = []
    for p in poses:
        img = np.zeros((96, 96, 3), np.uint8)
        img[:] = (40, 40, 60)
        for attr, dy, code, dx in p:
            g = spr[code]
            if attr & 0x4000: g = g[:, ::-1]
            if attr & 0x8000: g = g[::-1, :]
            col = ((attr & 0xf) | colbank) * 16
            for y in range(16):
                for x in range(16):
                    yy, xx = 72 + dy + y, 48 + dx + x
                    if g[y, x] and 0 <= yy < 96 and 0 <= xx < 96:
                        img[yy, xx] = pal[col + g[y, x]]
        img[72, 48] = (255, 0, 0)
        pv.append(img)
    Image.fromarray(np.concatenate(pv, 1)).save(f'{out}/enemies.png')
    print(f'{len(poses)} poses, {len(cells)} cells ({len(blob)} bytes), {len(pal_ids)} palettes; '
          + ', '.join(f'{n}: {len(s)} steps' for n, s in anims.items()))


if __name__ == '__main__':
    main()
