"""Build stage prop sprite data (breakable block, later items) for the PC Engine.

usage: pce_props.py block.snp outdir

Props are arcade objects that belong to the map rather than to the enemy
spawner: the brown block over the cave entrance in round 1 is one (object
slot 0, sprite cells $179.., spawned by marker $48 in the map). It is solid
until a down thrust breaks it (sim/scripts/block.txt), then it crumbles in
three steps of 6 frames and the gap under it opens.

Prop cells are not resident: the engine uploads a prop's cells to the props
area of VRAM when the prop comes on screen.

Outputs:
  props.bin    cells (128 bytes each, PCE sprite format)
  props.inc    PROP_CELLS, pose tables, animation tables, the stage's prop list
  proppal.bin  sprite palette for the props (16 colors)
  props.png    preview
"""
import os
import sys
import numpy as np
from PIL import Image
from arcade_gfx import load_region, decode_packed
from snap import read_snaps, palette_rgb
from enemy_capture import slot_pieces

ROMDIR = os.environ.get('RASTAN_ROMS', os.path.join(os.path.dirname(__file__), '..', 'roms', 'rastan'))

# (name, slot, first frame, last frame) in the block run.
SEQUENCES = [
    ('block', 0, 900, 900),
    ('block_break', 0, 913, 937),
]

# Round 1 props: (kind, world x, world y of the anchor). The block's anchor is
# the arcade object position (world x = screen x + 16 + camera).
PROPS = [
    ('PK_BLOCK', 814, 336),
]
# Solid box of the block, relative to its anchor: its 32x32 sprite, which covers
# the 32 px gap in the ground (x 800-831, rows 320-351) give or take 2 px.
BLOCK_BOX = (-16, -16, 16, 16)


def norm(p):
    mx = min(q[3] for q in p)
    my = min(q[1] for q in p)
    return tuple(sorted((a, dy - my, c, dx - mx) for a, dy, c, dx in p))


def to9(c):
    return tuple(int(round(int(v) * 7 / 255)) for v in c)


def main():
    snapf, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    spr = decode_packed(load_region(ROMDIR, 'pc090oj'), 16, 16).astype(int)
    want = {f for _, _, a, b in SEQUENCES for f in range(a, b + 1)}
    frames, pal, colbank = {}, None, None
    for s in read_snaps(snapf):
        if s.frame in want:
            frames[s.frame] = s
            if pal is None:
                pal, colbank = palette_rgb(s.pal), (s.sprctrl & 0xe0) >> 1

    poses, pose_ids, anims = [], {}, {}
    for name, slot, a, b in SEQUENCES:
        seq = []
        for f in range(a, b + 1):
            p = slot_pieces(frames[f], slot)
            if not p:
                continue
            k = norm(p)
            if k not in pose_ids:
                pose_ids[k] = len(poses)
                poses.append(p)
            pid = pose_ids[k]
            if seq and seq[-1][0] == pid:
                seq[-1][1] += 1
            else:
                seq.append([pid, 1])
        anims[name] = seq

    cells, cell_of, pals = [], {}, []
    for p in poses:
        for attr, dy, code, dx in p:
            ap = (attr & 0xf) | colbank
            if ap not in pals:
                pals.append(ap)
            if (code, ap) not in cell_of:
                cell_of[code, ap] = len(cells)
                cells.append((code, ap))
    assert len(pals) == 1, pals          # one PCE palette for the props
    assert len(cells) <= 16, len(cells)  # props area: 16 cells

    blob = bytearray()
    for code, ap in cells:
        g = spr[code]
        b = bytearray(128)
        for pl in range(4):
            for y in range(16):
                v = 0
                for x in range(16):
                    if (g[y, x] >> pl) & 1:
                        v |= 0x8000 >> x
                b[pl * 32 + y * 2] = v & 0xff
                b[pl * 32 + y * 2 + 1] = v >> 8
        blob += b
    open(f'{out}/props.bin', 'wb').write(blob)
    vce = bytearray()
    for i in range(16):
        r, g, b = to9(pal[pals[0] * 16 + i])
        vce += ((g << 6) | (r << 3) | b).to_bytes(2, 'little')
    open(f'{out}/proppal.bin', 'wb').write(vce)

    with open(f'{out}/props.inc', 'w') as f:
        f.write('; Generated by tools/pce_props.py\n')
        f.write(f'PROP_CELLS\t= {len(cells)}\n\n')
        f.write('; Pose: count, then per piece: dx, dy, cell, attr (bit 6 X flip, bit 7 Y flip)\n')
        for i, p in enumerate(poses):
            f.write(f'ppose_{i}:\t\tdb\t{len(p)}\n')
            for attr, dy, code, dx in p:
                a = (0x40 if attr & 0x4000 else 0) | (0x80 if attr & 0x8000 else 0)
                f.write(f'\t\tdb\t{dx & 0xff}, {dy & 0xff}, {cell_of[code, (attr & 0xf) | colbank]}, ${a:02X}\n')
        f.write('\nppose_table:\n')
        for i in range(len(poses)):
            f.write(f'\t\tdw\tppose_{i}\n')
        f.write('\n; Animations: (pose, frames) pairs, $FF end\n')
        for name, seq in anims.items():
            f.write(f'anim_{name}:\n')
            for pid, d in seq:
                f.write(f'\t\tdb\t{pid}, {d}\n')
            f.write('\t\tdb\t$FF, $FF\n')
        x0, y0, x1, y1 = BLOCK_BOX
        f.write(f'\nBLOCK_X0\t= {x0}\nBLOCK_Y0\t= {y0}\nBLOCK_X1\t= {x1}\nBLOCK_Y1\t= {y1}\n')
        f.write('\n; Stage props, by x: kind, x, y ($FF ends)\nstage_props:\n')
        for kind, x, y in PROPS:
            f.write(f'\t\tdb\t{kind}\n\t\tdw\t{x}, {y}\n')
        f.write('\t\tdb\t$FF\n')
        f.write(f'NUM_PROPS\t= {len(PROPS)}\n')

    pv = []
    for p in poses:
        img = np.full((48, 48, 3), (40, 40, 60), np.uint8)
        for attr, dy, code, dx in p:
            g = spr[code]
            if attr & 0x4000: g = g[:, ::-1]
            if attr & 0x8000: g = g[::-1, :]
            col = ((attr & 0xf) | colbank) * 16
            for y in range(16):
                for x in range(16):
                    if g[y, x]:
                        img[24 + dy + y, 24 + dx + x] = pal[col + g[y, x]]
        pv.append(img)
    Image.fromarray(np.concatenate(pv, 1)).save(f'{out}/props.png')
    print(f'{len(poses)} poses, {len(cells)} cells; ' + ', '.join(f'{n}: {len(s)} steps' for n, s in anims.items()))


if __name__ == '__main__':
    main()
